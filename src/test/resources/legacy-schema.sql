CREATE TABLE experience (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type ENUM('ACTIVITY','AWARD','CERTIFICATE','COMPETITION','EDUCATION','OVERSEAS','PAPER','PROJECT') NOT NULL,
  title VARCHAR(120) NOT NULL, organization VARCHAR(160), location VARCHAR(160),
  start_date DATE NOT NULL, end_date DATE, ongoing BOOLEAN NOT NULL,
  participants VARCHAR(300), role VARCHAR(200), description VARCHAR(10000),
  outcome VARCHAR(1000), tags VARCHAR(300), link VARCHAR(1000), featured BOOLEAN NOT NULL, demo BOOLEAN NOT NULL
);
